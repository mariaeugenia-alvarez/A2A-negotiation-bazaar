# 11. advise() against a simulated Abuela: any limit, any patience 4-7. Every price is a move, never above
#     what she would say next, and we end within 1 P of her limit as soon as her patience allows.
def abuela_sim(limit, patience, opening=30, our_limit=28):
    hist, her, seen = [], opening, set()
    for n in range(1, 12):
        adv = advise("abuela", "buy", "buy:pack:sobre_barrio", opening, hist, our_limit)
        if adv["action"] == "accept":
            return adv["price"], n
        p = adv["price"]
        assert p not in seen, (p, hist)  # no repeats: a repeated price earns nothing and she calls it spam
        seen.add(p)
        nxt = abuela_next(her, limit, "buy", first=not hist)
        if p >= nxt and p >= limit:  # she takes our offer
            return p, n
        her = nxt
        hist.append((p, her))
        if n >= patience or her == limit:  # her final: we take it
            return her, n
    return her, n


random.seed(7)
