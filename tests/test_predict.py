# 10. fit_chato recovers the schedule from conversations generated by it.
def chato_conv(steps, a, b, opening=97, tid=1):
    seq, ours, her, conceded = [D(opening)], 50, opening, 0
    for k, step in enumerate(steps, 1):
        ours += step or 0
        seq.append(U(ours))
        nxt = chato_next(her, conceded, k, step if k > 1 else None, a, b, "buy")
        conceded += her - nxt
        her = nxt
        seq.append(D(her))
    return thread(seq, dealer="chato", kind="buy:rare", tid=tid)


