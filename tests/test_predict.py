# 12. advise() against a simulated El Chato (his rare schedule): every price moves towards him, and with his
#     patience at 6+ answers we beat the 84 we got in thread 526 with steps of 4.
def chato_sim(patience, a=0.48, b=0.5, opening=97):
    hist, her, conceded, ours = [], opening, 0, None
    for k in range(1, 14):
        p = advise("chato", "buy", "buy:rare", opening, hist, 100)["price"]
        assert ours is None or p > ours, (k, p, ours)
        nxt = chato_next(her, conceded, k, None if ours is None else p - ours, a, b, "buy")
        if p >= nxt:  # he takes our offer
            return p
        conceded, her, ours = conceded + her - nxt, nxt, p
        hist.append((p, her))
        if k >= patience:
            return her
    return her


